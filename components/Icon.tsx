export type IconName = keyof typeof paths;

export function Icon({
  name,
  size = 20,
  filled = false,
  className = "",
  ...rest
}: { name: string; size?: number; filled?: boolean } & Omit<SVGProps<SVGSVGElement>, "name">) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={`shrink-0 ${className}`}
      {...rest}
    >
      {paths[name] ?? paths.box}
    </svg>
  );
}

// Picks an icon for a category from its slug/name, so new categories still get a sensible icon.
export function categoryIconName(slugOrName: string | null | undefined): string {
  const s = (slugOrName ?? "").toLowerCase();
  if (s.includes("bath") || s.includes("toilet") || s.includes("sink")) return "bath";
  if (s.includes("irrig") || s.includes("water") || s.includes("tank")) return "droplet";
  if (s.includes("paint") || s.includes("coat")) return "paint";
  if (s.includes("plumb") || s.includes("pipe")) return "plumbing";
  if (s.includes("steel") || s.includes("iron") || s.includes("metal")) return "steel";
  if (s.includes("tile") || s.includes("floor")) return "tiles";
  if (s.includes("tool") || s.includes("equip")) return "tools";
  return "box";
}

export function CategoryIcon({ slug, size = 18, className = "" }: { slug: string; size?: number; className?: string }) {
  return <Icon name={categoryIconName(slug)} size={size} className={className} />;
}
